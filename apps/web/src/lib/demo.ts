export type Difficulty = "starter" | "growing" | "challenge";
export type DemoQuestion = Question & {
  answer: number;
  explanation: string;
  difficulty: Difficulty;
  skill: string;
};
const q = (
  id: number,
  prompt: string,
  options: string[],
  answer: number,
  explanation: string,
  difficulty: Difficulty = "starter",
  skill = "",
): DemoQuestion => ({
  difficulty,
  skill,
  id,
  prompt,
  choices: options.map((text, i) => ({
    id: String.fromCharCode(97 + i),
    text,
  })),
  image_url: null,
  audio_url: null,
  image_alt: null,
  instruction: "Choose the best answer.",
  answer,
  explanation,
});
